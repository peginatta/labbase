"""Generated content inside the vault: box maps in box notes and Obsidian property types.

Generated blocks sit between markers and are rewritten on every run; everything else in the
note is left untouched.
"""

import json
from pathlib import Path

from labbase.vault import positions
from labbase.vault.crosscheck import box_grid, occupancy
from labbase.vault.model import Note, Vault
from labbase.vault.reader import split_frontmatter

START, END = "<!-- labbase:box-map start -->", "<!-- labbase:box-map end -->"

OBSIDIAN_TYPES = {
    "date": "date",
    "integer": "number",
    "number": "number",
    "boolean": "checkbox",
    "list": "multitext",
    "text": "text",
    "link": "text",
    "choice": "text",
    "id": "text",
}


def short_label(stock: Note) -> str:
    """Short text for a box cell: an item's code (primers), or the stock name without its
    date/person tail."""
    code = stock.props.get("code") if hasattr(stock, "props") else None
    if isinstance(code, str) and code.strip():
        return code.strip()[:16]
    words = stock.name.split()
    keep = []
    for w in words:
        if w[:4].isdigit() and "-" in w:  # stop at the date
            break
        keep.append(w)
    return " ".join(keep)[:16] or stock.name[:16]


def _table(rows: list[list[str]]) -> list[str]:
    """Markdown table padded the way Obsidian's table editor formats it (stable diffs)."""
    widths = [max(3, *(len(r[i]) for r in rows)) for i in range(len(rows[0]))]

    def line(cells: list[str]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths, strict=True)) + " |"

    return [line(rows[0]), line(["-" * w for w in widths]), *(line(r) for r in rows[1:])]


def box_map(vault: Vault, box: Note) -> str:
    rows, cols = box_grid(box)
    used = occupancy(vault).get(box.rel, {})
    table = [["", *(str(c + 1) for c in range(cols))]]
    for r in range(rows):
        cells = []
        for c in range(cols):
            stock = used.get(positions.label(r, c))
            cells.append(f"[[{stock.name}\\|{short_label(stock)}]]" if stock else "·")
        table.append([f"**{positions.label(r, 0)[0]}**", *cells])
    lines = [START, "", f"**Box map** ({len(used)} of {rows * cols} positions used)", ""]
    lines += _table(table)
    lines += ["", "*Generated by `labbase render` — edit the stock notes, not this map.*", "", END]
    return "\n".join(lines)


def replace_block(body: str, block: str) -> str:
    if START in body and END in body:
        before, rest = body.split(START, 1)
        _old, after = rest.split(END, 1)
        return before + block + after
    lines = body.split("\n")
    insert_at = next((i + 1 for i, line in enumerate(lines) if line.startswith("# ")), 0)
    lines[insert_at:insert_at] = ["", block, ""]
    return "\n".join(lines)


def render_box_maps(vault: Vault) -> list[Path]:
    changed = []
    for box in (n for n in vault.notes if n.type == "box"):
        text = box.path.read_text(encoding="utf-8")
        fm, body = split_frontmatter(text)
        head = text[: len(text) - len(body)]
        new = head + replace_block(body, box_map(vault, box))
        if new != text:
            box.path.write_text(new, encoding="utf-8")
            changed.append(box.path)
    return changed


def write_obsidian_types(vault: Vault) -> Path:
    """`.obsidian/types.json`: tells Obsidian which properties are dates, numbers, lists…"""
    types: dict[str, str] = {"aliases": "aliases", "tags": "tags"}
    for schema in [vault.common, *vault.schemas.values()]:
        for name, f in schema.fields.items():
            types.setdefault(name, OBSIDIAN_TYPES.get(f.kind, "text"))
    path = vault.root / ".obsidian" / "types.json"
    path.parent.mkdir(exist_ok=True)
    existing = json.loads(path.read_text()) if path.exists() else {}
    existing.setdefault("types", {}).update(types)
    path.write_text(json.dumps(existing, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path
