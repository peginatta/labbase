"""Generated content inside the vault: box maps in box notes and Obsidian property types.

Generated blocks sit between markers and are rewritten on every run; everything else in the
note is left untouched.
"""

import json
import re
from pathlib import Path

from labbase.vault import positions
from labbase.vault.crosscheck import box_grid, occupancy
from labbase.vault.model import Note, Vault
from labbase.vault.reader import split_frontmatter
from labbase.vault.writer import scalar

START, END = "<!-- labbase:box-map start -->", "<!-- labbase:box-map end -->"
WHERE_START, WHERE_END = "<!-- labbase:where start -->", "<!-- labbase:where end -->"
USAGE_START, USAGE_END = "<!-- labbase:usage start -->", "<!-- labbase:usage end -->"
CHANGE_FIELD = re.compile(r"(?i)\b(change|cambio)::")
CHANGE_WORDS = re.compile(
    r"(?i)\b(chang\w*|cambi\w*|modif\w*|instead|en vez|en lugar|increas\w*|decreas\w*|"
    r"aument\w*|reduc\w*|better|mejor|problem\w*|didn.t work|no funcion\w*|failed)\b"
)
PLACE_TYPES = ("location", "box")

OBSIDIAN_TYPES = {
    "date": "date",
    "integer": "number",
    "number": "number",
    "boolean": "checkbox",
    "list": "multitext",
    "text": "text",
    "link": "text",
    "choice": "text",
    "id": "text",
}


def short_label(stock: Note) -> str:
    """Short text for a box cell: an item's code (primers), or the stock name without its
    date/person tail."""
    code = stock.props.get("code") if hasattr(stock, "props") else None
    if isinstance(code, str) and code.strip():
        return code.strip()[:16]
    words = stock.name.split()
    keep = []
    for w in words:
        if w[:4].isdigit() and "-" in w:  # stop at the date
            break
        keep.append(w)
    return " ".join(keep)[:16] or stock.name[:16]


def _table(rows: list[list[str]]) -> list[str]:
    """Markdown table padded the way Obsidian's table editor formats it (stable diffs)."""
    widths = [max(3, *(len(r[i]) for r in rows)) for i in range(len(rows[0]))]

    def line(cells: list[str]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths, strict=True)) + " |"

    return [line(rows[0]), line(["-" * w for w in widths]), *(line(r) for r in rows[1:])]


def box_map(vault: Vault, box: Note) -> str:
    rows, cols = box_grid(box)
    used = occupancy(vault).get(box.rel, {})
    if not used:  # contents not inventoried by position: an empty grid would be misleading
        return "\n".join([START, "", "*No positions recorded for this box yet.*", "", END])
    table = [["", *(str(c + 1) for c in range(cols))]]
    for r in range(rows):
        cells = []
        for c in range(cols):
            stock = used.get(positions.label(r, c))
            cells.append(f"[[{stock.name}\\|{short_label(stock)}]]" if stock else "·")
        table.append([f"**{positions.label(r, 0)[0]}**", *cells])
    lines = [START, "", f"**Box map** ({len(used)} of {rows * cols} positions used)", ""]
    lines += _table(table)
    lines += [
        "",
        "*Generated by `labbase render` — edit the notes of what is in the box, not this map.*",
        "",
        END,
    ]
    return "\n".join(lines)


def replace_marked(body: str, start: str, end: str, block: str | None) -> str:
    """Replace the text between markers (inclusive) with `block`; insert it under the title
    if absent; remove it when `block` is None."""
    if start in body and end in body:
        before, rest = body.split(start, 1)
        _old, after = rest.split(end, 1)
        if block is None:
            sep = "\n\n" if before.strip() and after.strip() else "\n"
            return before.rstrip("\n") + sep + after.lstrip("\n")
        return before + block + after
    if block is None:
        return body
    lines = body.split("\n")
    insert_at = next((i + 1 for i, line in enumerate(lines) if line.startswith("# ")), 0)
    if start != WHERE_START and WHERE_END in lines:  # other blocks go below the location line
        insert_at = max(insert_at, lines.index(WHERE_END) + 1)
    after_blank = insert_at < len(lines) and lines[insert_at].strip() == ""
    new = (["", block] if insert_at else [block]) + ([] if after_blank else [""])
    lines[insert_at:insert_at] = new
    return "\n".join(lines)


def replace_block(body: str, block: str) -> str:
    return replace_marked(body, START, END, block)


def render_box_maps(vault: Vault) -> list[Path]:
    changed = []
    for box in (n for n in vault.notes if n.type == "box"):
        text = box.path.read_text(encoding="utf-8")
        fm, body = split_frontmatter(text)
        head = text[: len(text) - len(body)]
        if START in body and WHERE_START in body and body.index(START) < body.index(WHERE_START):
            body = replace_marked(body, START, END, None)  # map above the 📍 line: move it down
        new = head + replace_block(body, box_map(vault, box))
        if new != text:
            box.path.write_text(new, encoding="utf-8")
            changed.append(box.path)
    return changed


def place_of(vault: Vault, note: Note) -> tuple[Note | None, str]:
    """(the location/box this note is in, position text) — one step up the chain."""
    p = note.props
    if note.type in PLACE_TYPES:
        return vault.resolve(p.get("parent")), ""
    if note.type == "stock":
        box = vault.resolve(p.get("box"))
        if box is not None:
            raw = p.get("positions") if isinstance(p.get("positions"), list) else []
            pos = [positions.normalize(str(x)) for x in raw if x not in (None, "")]
            return box, ", ".join(x for x in pos if x)
        return vault.resolve(p.get("location")), ""
    place = vault.resolve(p.get("location"))
    pos = positions.normalize(str(p.get("position"))) if p.get("position") else None
    return place, pos or ""


def chain(vault: Vault, place: Note) -> list[Note]:
    """Places from the top (room) down to `place`."""
    nodes: list[Note] = []
    node: Note | None = place
    while node is not None and node.type in PLACE_TYPES and node not in nodes and len(nodes) < 20:
        nodes.append(node)
        node = place_of(vault, node)[0]
    return list(reversed(nodes))


def short_name(child: Note, parent: Note | None) -> str:
    """'Lab 3260 -20 horizontal, tower Leishmania I' under 'Lab 3260 -20 horizontal'
    -> 'tower Leishmania I'."""
    if parent is not None and child.name.lower().startswith(parent.name.lower()):
        rest = re.sub(r"^[\s,]+(?:[–—]\s+)?", "", child.name[len(parent.name) :]).strip()
        if rest:
            return rest
    return child.name


def _where_parts(vault: Vault, note: Note) -> tuple[list[tuple[Note, str]], str] | None:
    """[(place, short label) from the room down], position — or None when the note has no place."""
    place, pos = place_of(vault, note)
    if place is None or place.type not in PLACE_TYPES:
        return None
    parts, prev = [], None
    for n in chain(vault, place):
        parts.append((n, short_name(n, prev)))
        prev = n
    return parts, pos


def where_text(vault: Vault, note: Note) -> str | None:
    """Full location as plain text: 'Lab 3260 › -20 horizontal › … › Leishmania primers I › B9'."""
    found = _where_parts(vault, note)
    if found is None:
        return None
    parts, pos = found
    return " › ".join([label for _n, label in parts] + ([pos] if pos else []))


def where_block(vault: Vault, note: Note) -> str | None:
    """The same location as a clickable line under the title (📍 [[Lab 3260]] › …)."""
    found = _where_parts(vault, note)
    if found is None:
        return None
    parts, pos = found
    links = [f"[[{n.name}]]" if label == n.name else f"[[{n.name}|{label}]]" for n, label in parts]
    if pos:
        links.append(f"**{pos}**")
    return f"{WHERE_START}\n📍 " + " › ".join(links) + f"\n{WHERE_END}"


def set_property_line(text: str, key: str, value: str | None) -> str:
    """Set/remove one top-level property line in the frontmatter, leaving everything else as is.

    A new property is added after `position`/`positions`/`location`/`box`/`parent` when present,
    otherwise at the end of the properties."""
    fm, _body = split_frontmatter(text)
    if fm is None:
        return text
    lines = text.splitlines(keepends=True)
    end = 1 + len(fm.splitlines())  # index of the closing '---'
    prop_re = re.compile(rf"^{re.escape(key)}:(\s|$)")
    idx = next((i for i in range(1, end) if prop_re.match(lines[i])), None)
    if idx is not None:  # drop the old value, including indented continuation lines
        stop = idx + 1
        while (
            stop < end and lines[stop][:1] in (" ", "\t", "-") and not lines[stop].startswith("---")
        ):
            stop += 1
        del lines[idx:stop]
        end -= stop - idx
    if value is not None:
        new_line = f"{key}: {scalar(value)}\n"
        if idx is None:
            anchors = ("position", "positions", "location", "box", "parent")
            idx = end
            for i in range(1, end):
                if re.match(rf"^({'|'.join(anchors)}):(\s|$)", lines[i]):
                    idx = i + 1
        lines.insert(idx, new_line)
    return "".join(lines)


def render_where(vault: Vault) -> list[Path]:
    """Keep the generated location up to date on every note, in two forms:
    the plain-text `where` property (for tables/filters) and a clickable 📍 line under the title.
    Both are removed when the note has no place."""
    changed = []
    for note in vault.notes:
        if note.parse_error or not note.type:
            continue
        value = where_text(vault, note)
        block = where_block(vault, note)
        text = note.path.read_text(encoding="utf-8")
        new = text
        if block is not None or WHERE_START in new:
            _fm, body = split_frontmatter(new)
            head = new[: len(new) - len(body)]
            new = head + replace_marked(body, WHERE_START, WHERE_END, block)
        if note.props.get("where") != value:
            new = set_property_line(new, "where", value)
        if new != text:
            note.path.write_text(new, encoding="utf-8")
            changed.append(note.path)
    return changed


def _date_of(note: Note) -> str:
    from labbase.vault.validate import as_date

    d = as_date(note.props.get("date"))
    if d is not None:
        return d.isoformat()
    m = re.match(r"(\d{4}-\d{2}-\d{2})", note.name)
    return m.group(1) if m else ""


def usage_block(vault: Vault, protocol: Note) -> str:
    """Notebook entries linking to `protocol`: newest first, the line around each link,
    ⚠️ when the line proposes a change (`change::` / `cambio::` or words like "instead")."""
    link_re = re.compile(rf"\[\[{re.escape(protocol.name)}(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]", re.I)
    rows: list[tuple[str, str, str]] = []
    for note in vault.notes:
        if note.type != "note" or note is protocol:
            continue
        for line in note.path.read_text(encoding="utf-8").splitlines():
            if not link_re.search(line):
                continue
            text = re.sub(r"^\s*(?:[-*+]|\d+\.)\s+", "", line).strip()
            text = text if len(text) <= 200 else text[:199] + "…"
            flag = " ⚠️" if CHANGE_FIELD.search(line) or CHANGE_WORDS.search(line) else ""
            rows.append((_date_of(note), note.name, f"{text}{flag}"))
    rows.sort(key=lambda r: (r[0], r[1]), reverse=True)
    lines = [USAGE_START]
    if rows:
        lines += [f"- {d or 'undated'} · [[{name}]] — {text}" for d, name, text in rows]
    else:
        lines.append("*Not used in any notebook entry yet.*")
    lines.append(USAGE_END)
    return "\n".join(lines)


def render_usage(vault: Vault) -> list[Path]:
    """Keep the usage log of every protocol up to date (replaces the Dataview view)."""
    changed = []
    for note in (n for n in vault.notes if n.type == "protocol" and not n.parse_error):
        text = note.path.read_text(encoding="utf-8")
        block = usage_block(vault, note)
        if USAGE_START in text and USAGE_END in text:
            before, rest = text.split(USAGE_START, 1)
            after = rest.split(USAGE_END, 1)[1]
            new = before + block + after
        else:
            new = text.rstrip("\n") + "\n\n## Usage log\n\n" + block + "\n"
        if new != text:
            note.path.write_text(new, encoding="utf-8")
            changed.append(note.path)
    return changed


def write_obsidian_types(vault: Vault) -> Path:
    """`.obsidian/types.json`: tells Obsidian which properties are dates, numbers, lists…"""
    types: dict[str, str] = {"aliases": "aliases", "tags": "tags"}
    for schema in [vault.common, *vault.schemas.values()]:
        for name, f in schema.fields.items():
            types.setdefault(name, OBSIDIAN_TYPES.get(f.kind, "text"))
    path = vault.root / ".obsidian" / "types.json"
    path.parent.mkdir(exist_ok=True)
    existing = json.loads(path.read_text()) if path.exists() else {}
    existing.setdefault("types", {}).update(types)
    path.write_text(json.dumps(existing, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path
