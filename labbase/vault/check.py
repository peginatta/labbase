"""`labbase check`: run every check, compute statuses, write a report readable in Obsidian."""

from dataclasses import dataclass
from datetime import date
from pathlib import Path

from labbase.vault.crosscheck import check_links, check_positions, check_stocks
from labbase.vault.model import Vault
from labbase.vault.status import ContentTotal, Status, StockStatus, item_totals, stock_status
from labbase.vault.validate import ERROR, WARNING, Issue, check_fields

REPORT_PATH = "_reports/check.md"


@dataclass
class CheckResult:
    issues: list[Issue]
    statuses: list[StockStatus]
    totals: list[ContentTotal]

    @property
    def errors(self) -> list[Issue]:
        return [i for i in self.issues if i.level == ERROR]

    @property
    def warnings(self) -> list[Issue]:
        return [i for i in self.issues if i.level == WARNING]

    def attention(self) -> list[StockStatus]:
        return [s for s in self.statuses if s.status != Status.OK or s.expires_soon]


def run_checks(vault: Vault, today: date | None = None) -> CheckResult:
    issues = check_fields(vault) + check_links(vault) + check_stocks(vault) + check_positions(vault)
    issues.sort(key=lambda i: (i.level != ERROR, i.rel, i.field))
    statuses = [stock_status(vault, n, today) for n in vault.notes if n.type == "stock"]
    return CheckResult(issues, statuses, item_totals(vault, statuses))


def _link(rel: str) -> str:
    return f"[[{rel[:-3]}|{Path(rel).stem}]]" if rel.endswith(".md") else rel


def render_report(result: CheckResult, today: date | None = None) -> str:
    today = today or date.today()
    lines = [
        "# Vault check",
        "",
        "Generated by `labbase check` (rewritten on every run; the git history shows when).",
        "",
        f"**{len(result.errors)} errors · {len(result.warnings)} warnings · "
        f"{len(result.statuses)} stocks**",
        "",
    ]
    counts = {s: sum(1 for x in result.statuses if x.status == s) for s in Status}
    lines += [
        "| " + " | ".join(counts) + " |",
        "|" + "---|" * len(counts),
        "| " + " | ".join(str(v) for v in counts.values()) + " |",
        "",
    ]
    if result.issues:
        lines += ["## Problems to fix", "", "| | Note | Property | Problem |", "|---|---|---|---|"]
        for i in result.issues:
            icon = "❌" if i.level == ERROR else "⚠️"
            lines.append(f"| {icon} | {_link(i.rel)} | {i.field} | {i.message.replace('|', '/')} |")
        lines.append("")
    attention = result.attention()
    if attention:
        lines += ["## Stocks needing attention", "", "| Status | Stock | Why |", "|---|---|---|"]
        order = [Status.EXPIRED, Status.OUT, Status.LOW, Status.STALE, Status.OK]
        for s in sorted(attention, key=lambda x: (order.index(x.status), x.note.rel)):
            if s.status == Status.OUT:
                continue  # finished stocks are history, not a to-do
            lines.append(f"| {s.status} | {_link(s.note.rel)} | {s.reason} |")
        lines.append("")
    low = [t for t in result.totals if t.low]
    if low:
        lines += ["## Reorder", "", "| Item | Left |", "|---|---|"]
        lines += [f"| {_link(t.content.rel)} | {t.total:g} {t.unit} |" for t in low]
        lines.append("")
    return "\n".join(lines)


def write_report(vault: Vault, result: CheckResult, today: date | None = None) -> Path:
    path = vault.root / REPORT_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_report(result, today), encoding="utf-8")
    return path
