"""Generated Obsidian canvases (JSON Canvas 1.0): a lab map and one canvas per freezer.

Written to `_maps/` (an underscore folder, so not records). They are redrawn by
`labbase render`; manual layout changes are overwritten.
"""

import hashlib
import json
import re
from pathlib import Path

from labbase.vault.model import Note, Vault
from labbase.vault.reader import split_frontmatter

MAPS_DIR = "_maps"
FREEZER_DIR = "Freezers"
COLD_KINDS = ("freezer", "fridge", "incubator", "cabinet")
COLOR = {-80: "5", -20: "4", 4: "3"}  # cyan, green, yellow (Obsidian presets)
NOTICE = "*Generated by `labbase render` — moving cards here is overwritten. Edit the notes.*"


def _id(*parts: str) -> str:
    return hashlib.sha1("|".join(parts).encode()).hexdigest()[:16]


def _text(key: str, x: int, y: int, w: int, h: int, text: str, color: str = "") -> dict:
    node = {
        "id": _id("t", key),
        "type": "text",
        "x": x,
        "y": y,
        "width": w,
        "height": h,
        "text": text,
    }
    if color:
        node["color"] = color
    return node


def _group(key: str, x: int, y: int, w: int, h: int, label: str, color: str = "") -> dict:
    node = {
        "id": _id("g", key),
        "type": "group",
        "x": x,
        "y": y,
        "width": w,
        "height": h,
        "label": label,
    }
    if color:
        node["color"] = color
    return node


class Tree:
    """Parent/children relations between locations and boxes."""

    def __init__(self, vault: Vault) -> None:
        self.vault = vault
        self.places = [n for n in vault.notes if n.type in ("location", "box")]
        self.children: dict[str, list[Note]] = {}
        self.roots: list[Note] = []
        for n in self.places:
            parent = vault.resolve(n.props.get("parent"))
            if parent is None or parent.type not in ("location", "box"):
                self.roots.append(n)
            else:
                self.children.setdefault(parent.rel, []).append(n)
        for kids in self.children.values():
            kids.sort(key=_natural)
        self.roots.sort(key=_natural)

    def kids(self, n: Note) -> list[Note]:
        return self.children.get(n.rel, [])


def _natural(n: Note) -> list:
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", n.name)]


def _short(child: Note, parent: Note | None) -> str:
    if parent is not None and child.name.lower().startswith(parent.name.lower()):
        rest = re.sub(r"^[\s,]+", "", child.name[len(parent.name) :]).strip()
        if rest:
            return rest
    return child.name


def _link(n: Note, label: str) -> str:
    return f"[[{n.name}]]" if label == n.name else f"[[{n.name}|{label}]]"


def _color(n: Note) -> str:
    t = n.props.get("temperature_C")
    return COLOR.get(int(t), "") if isinstance(t, int | float) else ""


def sections(tree: Tree, freezer: Note) -> list[tuple[str, Note | None, list[Note]]]:
    """(label, holder, boxes) for every place inside `freezer` that holds boxes, depth-first;
    boxes directly in the freezer come last with holder None. Labels are paths like
    'shelf 2 › rack 1'."""
    out: list[tuple[str, Note | None, list[Note]]] = []

    def walk(node: Note, parent: Note, prefix: str) -> None:
        label = (prefix + " › " if prefix else "") + _short(node, parent)
        kids = tree.kids(node)
        boxes = [k for k in kids if k.type == "box"]
        places = [k for k in kids if k.type != "box"]
        if boxes or not places:
            out.append((label, node, boxes))
        for p in places:
            walk(p, node, label)

    for k in tree.kids(freezer):
        if k.type != "box":
            walk(k, freezer, "")
    direct = [k for k in tree.kids(freezer) if k.type == "box"]
    if direct:
        out.append(("", None, direct))
    return out


def _box_title(box: Note, parent: Note | None) -> str:
    label = str(box.props.get("label") or "").strip()
    short = _short(box, parent)
    short = short[:1].upper() + short[1:]
    return f"{short} — {label}" if label and label.lower() not in short.lower() else short


def box_summary(box: Note, max_lines: int = 3, width: int = 60) -> list[str]:
    """A few lines describing a box: its Contents bullets, or the first paragraph of text."""
    text = box.path.read_text(encoding="utf-8")
    _fm, body = split_frontmatter(text)
    body = re.sub(
        r"<!-- labbase:[\w-]+ start -->.*?<!-- labbase:[\w-]+ end -->", "", body, flags=re.S
    )
    lines: list[str] = []
    if "## Contents" in body:
        section = body.split("## Contents", 1)[1].split("\n## ", 1)[0]
        lines = [ln[2:].strip() for ln in section.splitlines() if ln.startswith("- ")]
        lines = [ln for ln in lines if not ln.startswith("(no description")]
    else:
        for para in re.split(r"\n\s*\n", body):
            p = para.strip()
            if p and not p.startswith(("#", "```", "|", "*Generated")):
                lines = [" ".join(p.split())]
                break
    return [ln if len(ln) <= width else ln[: width - 1] + "…" for ln in lines[:max_lines]]


# --- lab map ----------------------------------------------------------------------------------
COL_W, CARD_H, BOX_H, GAP, PAD, HEAD = 300, 60, 40, 30, 20, 60


FREEZER_W, FREEZER_H = 280, 110


def has_canvas(tree: Tree, n: Note) -> bool:
    return n.props.get("kind") in COLD_KINDS and bool(tree.kids(n))


def canvas_path(n: Note) -> str:
    return f"{MAPS_DIR}/{FREEZER_DIR}/{n.name}.canvas"


def _summary(tree: Tree, freezer: Note) -> str:
    """'19 boxes · tower 5, tower 6' — what is recorded inside a freezer."""
    secs = sections(tree, freezer)
    boxes = sum(len(b) for _l, _h, b in secs)
    holders = [label for label, h, _b in secs if h is not None]
    if not boxes and not holders:
        return "*nothing recorded yet*"
    text = f"{boxes} box{'es' if boxes != 1 else ''}"
    if holders:
        shown = ", ".join(holders[:4]) + (f" +{len(holders) - 4} more" if len(holders) > 4 else "")
        text += f" · {shown}"
    return text


def lab_map(vault: Vault) -> dict:
    """Rooms and their freezers only; each freezer card links to that freezer's canvas."""
    tree = Tree(vault)
    nodes: list[dict] = [_text("notice", 0, -120, 700, 60, NOTICE)]
    x = 0
    for room in tree.roots:
        freezers = [k for k in tree.kids(room) if k.props.get("kind") in COLD_KINDS]
        width = max(len(freezers), 1) * (FREEZER_W + GAP) - GAP + 2 * PAD
        height = HEAD + CARD_H + FREEZER_H + 2 * PAD
        nodes.insert(0, _group(room.rel, x, 0, width, height, room.name))
        nodes.append(
            _text(
                room.rel,
                x + PAD,
                15,
                min(width - 2 * PAD, 400),
                CARD_H - 10,
                f"## {_link(room, room.name)}",
            )
        )
        fx = x + PAD
        for f in freezers:
            label = _short(f, room)
            target = f"[[{canvas_path(f)}|{label}]]" if has_canvas(tree, f) else _link(f, label)
            nodes.append(
                _text(
                    f.rel,
                    fx,
                    HEAD + CARD_H,
                    FREEZER_W,
                    FREEZER_H,
                    f"### {target}\n{_summary(tree, f)}",
                    _color(f),
                )
            )
            fx += FREEZER_W + GAP
        x += width + 2 * GAP
    groups = [n for n in nodes if n["type"] == "group"]
    return {"nodes": groups + [n for n in nodes if n["type"] != "group"], "edges": []}


# --- one canvas per freezer --------------------------------------------------------------------
BOX_W, BOX_CARD_H, PER_COLUMN = 340, 150, 10


def freezer_canvas(vault: Vault, freezer: Note) -> dict:
    tree = Tree(vault)
    nodes: list[dict] = [
        _text("back", 0, -280, 300, 60, f"[[{MAPS_DIR}/Lab map.canvas|← Lab map]]"),
        _text("title", 0, -200, 700, 70, f"# {_link(freezer, freezer.name)}", _color(freezer)),
        _text("notice", 0, -120, 700, 60, NOTICE),
    ]
    columns: list[tuple[str, Note | None, list[Note]]] = []
    for label, holder, boxes in sections(tree, freezer):
        if holder is not None:
            columns.append((label, holder, boxes))
            continue
        for i in range(0, len(boxes), PER_COLUMN):
            chunk = boxes[i : i + PER_COLUMN]
            many = len(boxes) > PER_COLUMN
            name = f"boxes {_box_num(chunk[0])}–{_box_num(chunk[-1])}" if many else "boxes"
            columns.append((name, None, chunk))
    x = 0
    for label, holder, boxes in columns:
        height = HEAD + max(len(boxes), 1) * (BOX_CARD_H + 10) + PAD
        nodes.insert(0, _group(f"{freezer.rel}>{label}", x, 0, BOX_W + 2 * PAD, height, label))
        if holder is not None:
            nodes.append(_text(holder.rel, x + PAD, 12, BOX_W, 40, _link(holder, label)))
        y = HEAD
        for b in boxes:
            lines = [f"**{_link(b, _box_title(b, holder or freezer))}**"]
            lines += [f"- {ln}" for ln in box_summary(b)] or ["*(no description)*"]
            nodes.append(_text(b.rel, x + PAD, y, BOX_W, BOX_CARD_H, "\n".join(lines)))
            y += BOX_CARD_H + 10
        if not boxes:
            nodes.append(_text(f"{label}-empty", x + PAD, y, BOX_W, 50, "*(no boxes recorded)*"))
        x += BOX_W + 2 * PAD + GAP
    groups = [n for n in nodes if n["type"] == "group"]
    return {"nodes": groups + [n for n in nodes if n["type"] != "group"], "edges": []}


def _box_num(b: Note) -> str:
    m = re.search(r"box (\d+)$", b.name)
    return m.group(1) if m else b.name


def _write(path: Path, data: dict) -> bool:
    text = json.dumps(data, indent="\t", ensure_ascii=False) + "\n"
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def render_canvases(vault: Vault) -> list[Path]:
    """Write `_maps/Lab map.canvas` and `_maps/Freezers/<freezer>.canvas`; remove stale ones."""
    root = vault.root / MAPS_DIR
    changed: list[Path] = []
    if not any(n.type in ("location", "box") for n in vault.notes):
        return changed
    lab = root / "Lab map.canvas"
    if _write(lab, lab_map(vault)):
        changed.append(lab)
    tree = Tree(vault)
    wanted: set[Path] = set()
    for f in (n for n in tree.places if n.props.get("kind") in COLD_KINDS):
        if not tree.kids(f):
            continue
        path = root / FREEZER_DIR / f"{f.name}.canvas"
        wanted.add(path)
        if _write(path, freezer_canvas(vault, f)):
            changed.append(path)
    folder = root / FREEZER_DIR
    if folder.exists():
        for old in folder.glob("*.canvas"):
            if old not in wanted:
                old.unlink()
                changed.append(old)
    return changed
